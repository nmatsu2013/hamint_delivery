const COLUMN_META = new Map<
  string,
  { label: string; dataType: MasterColumnDataType }
>();

function register(labels: Record<string, string>, dataType: MasterColumnDataType): void {
  for (const [name, label] of Object.entries(labels)) {
    COLUMN_META.set(name, { label, dataType });
  }
}

register(TEXT_LABELS, 'text');
register(DATE_LABELS, 'date');
register(TIMESTAMP_LABELS, 'timestamptz');
register(NUMERIC_LABELS, 'numeric');
register(INTEGER_LABELS, 'integer');
register(UUID_LABELS, 'uuid');
register(BOOLEAN_LABELS, 'boolean');
register(JSON_LABELS, 'jsonb');

function metaOf(name: string): { label: string; dataType: MasterColumnDataType } {
  const meta = COLUMN_META.get(name);
  if (meta) {
    return meta;
  }
  return { label: name, dataType: 'text' };
}

interface TableInput {
  name: string;
  label: string;
  category: MasterTableCategory;
  description: string;
  hasActiveFlag?: boolean;
  defaultSort: string;
  defaultOrder: 'asc' | 'desc';
  defaultSecondarySort?: string;
  columns: string[];
  hiddenColumns?: string[];
  requiredColumns?: string[];
  foreignKeys?: MasterForeignKeyDefinition[];
}

function defineTable(input: TableInput): MasterTableDefinition {
  const hidden = new Set(input.hiddenColumns ?? ['id', 'created_by', 'updated_by']);
  const required = new Set(input.requiredColumns ?? []);
  const foreignKeys = new Map(
    (input.foreignKeys ?? []).map((foreignKey) => [foreignKey.column, foreignKey.target]),
  );
  const systemColumns = new Set(['id', 'created_at', 'updated_at', 'created_by', 'updated_by']);
  const columns = input.columns.map((name) => {
    const meta = metaOf(name);
    return {
      name,
      label: meta.label,
      dataType: meta.dataType,
      sortable: meta.dataType !== 'jsonb',
      visible: !hidden.has(name),
      searchable: meta.dataType !== 'jsonb' && meta.dataType !== 'boolean',
      editable: input.category === 'master' && !systemColumns.has(name),
      required: required.has(name),
      foreignKeyTarget: foreignKeys.get(name),
    };
  });
  return {
    name: input.name,
    label: input.label,
    category: input.category,
    description: input.description,
    hasActiveFlag: input.hasActiveFlag ?? true,
    defaultSort: input.defaultSort,
    defaultOrder: input.defaultOrder,
    defaultSecondarySort: input.defaultSecondarySort,
    columns,
    foreignKeys: input.foreignKeys ?? [],
  };
}

